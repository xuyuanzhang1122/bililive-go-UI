const fs = require('fs');
const ts = require('../../src/webapp/node_modules/typescript');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS }}).outputText, filename);
global.window = { location: { origin: 'https://local.test' } };
global.localStorage = { getItem: () => 'test-management-key' };
(async () => {
 const assert = require('assert/strict');
 const { authFetch } = require('../../src/webapp/src/utils/common.ts');
 let calls = [];
 global.fetch = async (...args) => { calls.push(args); return new Response('{}'); };
 await authFetch('https://external.test/api/test');
 assert.equal(new Headers(calls[0][1].headers).get('Authorization'), null, '管理 Key 不可发送到外站');
 await authFetch('/api/test');
 assert.equal(new Headers(calls[1][1].headers).get('Authorization'), 'Bearer test-management-key');
 const { SSEDecoder, SSEManager } = require('../../src/webapp/src/utils/sse.ts');
 const events = [];
 const decoder = new SSEDecoder((type, data) => events.push([type, JSON.parse(data)]));
 const bytes = new TextEncoder().encode(': ping\r\nevent: live_update\r\ndata: {"room_id":"测试",\r\ndata: "data":1}\r\n\r\n');
 for (const byte of bytes) decoder.push(new Uint8Array([byte]));
 assert.deepEqual(events, [['live_update', {room_id:'测试',data:1}]], '分块 UTF8、CRLF、多行 data');
 let cancelled = false;
 global.fetch = async (url, init) => { calls.push([url,init]); return new Response(new ReadableStream({ start(c) { c.enqueue(new TextEncoder().encode('event: live_update\ndata: {"room_id":"x","data":2}\n\n')); }, cancel(){cancelled = true;} }), {headers:{'Content-Type':'text/event-stream'}}); };
 const manager = new SSEManager();
 const seen=[]; const id=manager.subscribe('*','live_update',m=>seen.push(m.data));
 await new Promise(r=>setTimeout(r,20));
 assert.deepEqual(seen,[2]);
 const [url,init]=calls[calls.length-1];
 assert.equal(url,'https://local.test/api/sse'); assert.equal(new Headers(init.headers).get('Authorization'),'Bearer test-management-key');
 manager.unsubscribe(id); await new Promise(r=>setTimeout(r,20));
 assert(init.signal.aborted); assert(cancelled); assert.equal(manager.getSubscriberCount(),0); assert.equal(manager.isConnected(),false);
 console.log('PASS: Web 鉴权与 SSE 流分块、分发、取消');
})().catch(e=>{console.error(e);process.exitCode=1;});
