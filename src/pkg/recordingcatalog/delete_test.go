package recordingcatalog

import (
	"context"
	"github.com/stretchr/testify/require"
	"os"
	"path/filepath"
	"testing"
)

func TestDeleteRecordingRejectsChangedAndActiveSourcesBeforeDeleting(t *testing.T) {
	ctx := context.Background()
	root := t.TempDir()
	path := filepath.Join(root, "平台", "主播", "source.flv")
	other := filepath.Join(root, "平台", "主播", "other.flv")
	require.NoError(t, os.MkdirAll(filepath.Dir(path), 0755))
	require.NoError(t, os.WriteFile(path, []byte("source"), 0600))
	require.NoError(t, os.WriteFile(other, []byte("other"), 0600))
	store, err := Open(filepath.Join(t.TempDir(), "catalog.db"), root)
	require.NoError(t, err)
	m := NewManager(store, 0)
	defer m.Close()
	require.NoError(t, m.Reconcile(ctx))
	e, err := store.Lookup(ctx, "平台/主播/source.flv")
	require.NoError(t, err)
	n, err := m.DeleteRecording(ctx, e.RecordingID, "wrong version")
	require.ErrorIs(t, err, ErrPlaybackChanged)
	require.Zero(t, n)
	require.FileExists(t, path)
	end := BeginRecording(path)
	n, err = m.DeleteRecording(ctx, e.RecordingID, e.SourceVersion)
	require.ErrorIs(t, err, ErrRecordingActive)
	require.Zero(t, n)
	end()
	require.FileExists(t, path)
	require.NoError(t, os.WriteFile(path, []byte("changed source"), 0600))
	n, err = m.DeleteRecording(ctx, e.RecordingID, e.SourceVersion)
	require.ErrorIs(t, err, ErrPlaybackChanged)
	require.Zero(t, n)
	require.FileExists(t, path)
	require.FileExists(t, other)
	require.NoError(t, m.Reconcile(ctx))
	current, err := m.PlaybackRecording(ctx, e.RecordingID)
	require.NoError(t, err)
	n, err = m.DeleteRecording(ctx, current.RecordingID, current.SourceVersion)
	require.NoError(t, err)
	require.Equal(t, 1, n)
	require.NoFileExists(t, path)
	require.FileExists(t, other)
	status, err := m.Status(ctx)
	require.NoError(t, err)
	require.Equal(t, "pending", status, "删除后不能沿用旧统计作当前核验值")
	require.NoError(t, m.Reconcile(ctx))
	list, err := m.ListRecordings(ctx, "", 100)
	require.NoError(t, err)
	require.Len(t, list, 1)
}
func TestDeleteRecordingRejectsSymlinkReplacement(t *testing.T) {
	ctx := context.Background()
	root := t.TempDir()
	path := filepath.Join(root, "平台", "主播", "source.flv")
	require.NoError(t, os.MkdirAll(filepath.Dir(path), 0755))
	require.NoError(t, os.WriteFile(path, []byte("source"), 0600))
	store, err := Open(filepath.Join(t.TempDir(), "catalog.db"), root)
	require.NoError(t, err)
	m := NewManager(store, 0)
	defer m.Close()
	require.NoError(t, m.Reconcile(ctx))
	e, err := store.Lookup(ctx, "平台/主播/source.flv")
	require.NoError(t, err)
	outside := filepath.Join(t.TempDir(), "important.flv")
	require.NoError(t, os.WriteFile(outside, []byte("outside"), 0600))
	require.NoError(t, os.Remove(path))
	require.NoError(t, os.Symlink(outside, path))
	n, err := m.DeleteRecording(ctx, e.RecordingID, e.SourceVersion)
	require.Error(t, err)
	require.Zero(t, n)
	data, err := os.ReadFile(outside)
	require.NoError(t, err)
	require.Equal(t, "outside", string(data))
}
